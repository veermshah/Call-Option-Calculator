// Downloads the instrument samples listed in src/shared/instruments.ts into
// src/renderer/public/samples and measures their levels.
//
//   node scripts/fetch-samples.mjs
//
// Needs ffmpeg on PATH. Already-downloaded files are skipped.
//
// Sources (both allow commercial use and redistribution; see
// src/renderer/public/samples/CREDITS.md):
// - Melodic instruments: FluidR3_GM by Frank Wen, rendered per note by
//   github.com/gleitz/midi-js-soundfonts.
// - Drum kits: Sonic Pi's sample library (CC0), github.com/sonic-pi-net/sonic-pi.

import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { runnerImport } from 'vite'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'src/renderer/public/samples')
const FLUID = 'https://raw.githubusercontent.com/gleitz/midi-js-soundfonts/gh-pages/FluidR3_GM'
const SONIC_PI = 'https://raw.githubusercontent.com/sonic-pi-net/sonic-pi/main/etc/samples'

// Loudness the sampled instruments are matched to (RMS of the first 0.6 s, dBFS).
const TARGET_RMS_DB = -18
// Never boost a sample so far that its peak would pass this.
const MAX_PEAK_DB = -1

const { module: inst } = await runnerImport(join(root, 'src/shared/instruments.ts'), {
  configFile: false,
  resolve: { alias: { '@shared': join(root, 'src/shared') } }
})

async function download(url, file) {
  if (existsSync(file)) return
  mkdirSync(dirname(file), { recursive: true })
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(url)
    if (res.ok) {
      writeFileSync(file, Buffer.from(await res.arrayBuffer()))
      return
    }
    if (attempt >= 3) throw new Error(`${res.status} ${url}`)
    await new Promise((r) => setTimeout(r, 1000 * attempt))
  }
}

/** Mono 16-bit samples of the first `seconds` of a file. */
function decode(file, seconds) {
  const args = ['-v', 'error', '-i', file, '-ac', '1', '-ar', '44100', '-f', 's16le']
  if (seconds) args.push('-t', String(seconds))
  const raw = execFileSync('ffmpeg', [...args, '-'], { maxBuffer: 64 << 20 })
  return new Int16Array(raw.buffer, raw.byteOffset, raw.length >> 1)
}

function levels(file, seconds) {
  const s = decode(file, seconds)
  let sum = 0
  let peak = 0
  for (const x of s) {
    sum += x * x
    peak = Math.max(peak, Math.abs(x))
  }
  const db = (v) => 20 * Math.log10(Math.max(v, 1) / 32768)
  return { rms: db(Math.sqrt(sum / Math.max(1, s.length))), peak: db(peak) }
}

const round1 = (n) => Math.round(n * 10) / 10

// --- Melodic instruments ---------------------------------------------------
const gains = {}
const sampled = inst.CATALOG.filter((d) => d.kind === 'sampled')
for (const def of sampled) {
  const notes = inst.sampleNotes(def)
  await Promise.all(
    notes.map((m) => {
      const name = inst.sampleNoteName(m)
      return download(`${FLUID}/${def.sample}-mp3/${name}.mp3`, join(out, def.sample, `${name}.mp3`))
    })
  )
  // Measure at the recorded note nearest the middle of the instrument's home register.
  const mid = (def.home[0] + def.home[1]) / 2
  const ref = notes.reduce((a, b) => (Math.abs(b - mid) < Math.abs(a - mid) ? b : a))
  const { rms, peak } = levels(join(out, def.sample, `${inst.sampleNoteName(ref)}.mp3`), 0.6)
  gains[def.id] = round1(Math.min(TARGET_RMS_DB - rms, MAX_PEAK_DB - peak))
  console.log(`${def.id.padEnd(18)} ${notes.length} notes  rms ${round1(rms)} peak ${round1(peak)} -> ${gains[def.id]} dB`)
}

writeFileSync(
  join(root, 'src/shared/sampleLevels.ts'),
  `// Generated by scripts/fetch-samples.mjs: level correction in dB per sampled\n` +
    `// instrument so they sit at a similar loudness. Re-run the script to update.\n` +
    `export const SAMPLE_GAIN_DB: Record<string, number> = ${JSON.stringify(gains, null, 2).replace(/"([a-z0-9-]+)":/g, "'$1':")}\n`
)

// --- Drum kits -------------------------------------------------------------
// Converted to 16-bit mono WAV (no decoder padding, so hits land on time),
// peak-normalised, and long tails faded out at 2.5 s.
const drumFiles = new Set()
for (const def of inst.CATALOG) if (def.kind === 'kit' && def.sounds) for (const f of Object.values(def.sounds)) drumFiles.add(f)
const tmp = join(root, 'node_modules/.cache/riff-samples')
for (const name of drumFiles) {
  const wav = join(out, 'drums', `${name}.wav`)
  if (existsSync(wav)) continue
  const flac = join(tmp, `${name}.flac`)
  await download(`${SONIC_PI}/${name}.flac`, flac)
  const { peak } = levels(flac)
  const gain = round1(MAX_PEAK_DB - peak)
  mkdirSync(dirname(wav), { recursive: true })
  execFileSync('ffmpeg', [
    '-v', 'error', '-y', '-i', flac, '-ac', '1', '-ar', '44100',
    '-af', `volume=${gain}dB,afade=t=out:st=2.2:d=0.3`, '-t', '2.5', '-c:a', 'pcm_s16le', wav
  ])
  console.log(`drums/${name}.wav  ${gain > 0 ? '+' : ''}${gain} dB`)
}

console.log('Done. Keep src/renderer/public/samples/CREDITS.md up to date when adding sources.')
